// public/sounds/*.mp3 각 파일의 내용 해시를 계산해 src/audio/soundHashes.ts로 내보낸다.
// 캐시버스팅용 — 파일이 바뀌면 해시(?v=)가 바뀌어 브라우저·CDN이 그 파일만 정확히 리페치한다.
// 실행: `npm run sounds:hash` (사운드 재생성 후) — build:static / sounds:fetch가 자동 호출.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const soundsDir = join(root, "public", "sounds");

const files = readdirSync(soundsDir)
  .filter((f) => f.endsWith(".mp3"))
  .sort();

const hashes = {};
for (const f of files) {
  const h = createHash("sha1").update(readFileSync(join(soundsDir, f))).digest("hex").slice(0, 8);
  hashes[f.replace(/\.mp3$/, "")] = h; // 키 = 파일 스템 (예: "ui-click", "bgm-menu")
}

const out =
  "// AUTO-GENERATED by scripts/gen-sound-hashes.mjs — 손으로 편집하지 말 것.\n" +
  "// 사운드 파일 내용 해시. soundManager가 로드 URL에 ?v=<hash>로 붙여 캐시를 무효화한다.\n" +
  "export const SOUND_HASHES: Record<string, string> = " +
  JSON.stringify(hashes, null, 2) +
  ";\n";

writeFileSync(join(root, "src", "audio", "soundHashes.ts"), out);
process.stdout.write(`✓ soundHashes.ts (${files.length} files)\n`);
